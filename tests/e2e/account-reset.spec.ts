import { expect, test } from '@playwright/test'

test('после регистрации без кода можно вступить в команду и начать аккаунт заново при входе', async ({ page }) => {
  const suffix = crypto.randomUUID()
  const password = 'test-password-2026'
  await page.goto('/register?role=manager')
  await page.getByLabel('Имя и фамилия').fill('Руководитель Сброса')
  await page.getByLabel('Email', { exact: true }).fill(`reset-manager-${suffix}@example.test`)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Зарегистрироваться' }).click()
  await page.getByLabel('Название команды').fill('Команда перезапуска')
  await page.getByRole('button', { name: 'Создать команду' }).click()
  const code = (await page.getByLabel('Код приглашения').innerText()).trim()
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()

  const email = `reset-employee-${suffix}@example.test`
  await page.goto('/register?role=employee')
  await page.getByLabel('Имя и фамилия').fill('Сотрудник Сброса')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Зарегистрироваться' }).click()
  await expect(page.getByRole('heading', { name: 'Создайте своего героя' })).toBeVisible()
  const { user } = await page.evaluate(async () => (await fetch('/api/auth/me')).json())
  await page.evaluate((id: string) => localStorage.setItem(`bi-academy:user:${id}:bi-academy:attempts`, 'old draft'), user.id)
  await page.goto('/account')
  await page.getByLabel('Код команды', { exact: true }).fill(code)
  await page.getByRole('checkbox', { name: /Согласен\(на\) передать руководителю/ }).check()
  await page.getByRole('button', { name: 'Присоединиться' }).click()
  await expect(page.getByRole('heading', { name: 'Команда перезапуска' })).toBeVisible()
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()

  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('checkbox', { name: 'Начать заново при входе' }).check()
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL('/avatar/setup')
  expect(await page.evaluate((id: string) => localStorage.getItem(`bi-academy:user:${id}:bi-academy:attempts`), user.id)).toBeNull()
  await page.goto('/account')
  await expect(page.getByRole('button', { name: 'Присоединиться' })).toBeVisible()
  await page.getByLabel('Код команды', { exact: true }).fill(code)
  await page.getByRole('checkbox', { name: /Согласен\(на\) передать руководителю/ }).check()
  await page.getByRole('button', { name: 'Присоединиться' }).click()
  await expect(page.getByRole('heading', { name: 'Команда перезапуска' })).toBeVisible()
})
