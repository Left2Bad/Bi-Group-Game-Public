const questionId = (index: number) => `Q${String(index + 1).padStart(2, '0')}`

export const questions: readonly Question[] = situations.map(([trait, secondaryTrait, context, text, choices], index) => {
  const id = questionId(index)
  return { id, trait, secondaryTrait, context, text, options: choices.map(([label], optionIndex) => ({
    id: `${id}-${'ABCD'[optionIndex]}`, text: label,
  })) as unknown as Question['options'] }
})

/** По одному правилу на пару «вариант × качество»: 15 × 4 × 2 = 120 правил. */
export const scoring: readonly ScoringRule[] = situations.flatMap(([primary, secondary, , , choices], index) => {
  const id = questionId(index)
  return choices.flatMap(([, [primaryPoints, secondaryPoints], reason], optionIndex) => {
    const optionId = `${id}-${'ABCD'[optionIndex]}`
    return [
      { questionId: id, optionId, trait: primary, points: primaryPoints, reason, developmentTag: `${id}:${primary}` },
      { questionId: id, optionId, trait: secondary, points: secondaryPoints, reason, developmentTag: `${id}:${secondary}` },
    ]
  })
})
